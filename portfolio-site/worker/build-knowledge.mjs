// Turns the notes the website already uses (../assets/ask.js) into retrieval chunks for the worker.
// Run after you edit any answer:  node build-knowledge.mjs   (or: npm run build)
import fs from "node:fs";
import vm from "node:vm";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const src = fs.readFileSync(path.join(here, "..", "assets", "ask.js"), "utf8");
const sandbox = { window: {}, document: { querySelector: () => null, getElementById: () => null } };
vm.runInNewContext(src, sandbox);
const A = sandbox.window.askAryan;
if (!A || !A.notes) throw new Error("Could not read notes from assets/ask.js");

const strip = (h) => String(h || "")
  .replace(/<button[^>]*>.*?<\/button>/g, "")
  .replace(/<li>/g, "\n- ").replace(/<\/p>\s*<p>/g, "\n\n")
  .replace(/<[^>]+>/g, "").replace(/&amp;/g, "&").replace(/\\"/g, '"')
  .replace(/[ \t]+\n/g, "\n").trim();
const site = "https://ryansingh0.github.io/";
const links = (l) => (Array.isArray(l) ? l.map(([t, u]) => ({ t, u: u.startsWith("#") ? site + u : u })) : []);

const chunks = [];
for (const n of A.notes) {
  if (!n.a) continue;
  chunks.push({
    id: n.id,
    keys: n.k.map((k) => k.replace(/^!/, "")),
    text: strip(n.a) + (A.more[n.id] ? "\n\nMore: " + strip(A.more[n.id]) : ""),
    links: links(n.l)
  });
}
for (const [fam, P] of Object.entries(A.pitch)) {
  chunks.push({
    id: "pitch-" + fam,
    keys: ["why hire", P.label, fam],
    text: `Why hire Aryan for ${P.label} roles:\n- ` + P.t1.map(strip).join("\n- ") + "\n\nMore: " + strip(P.t2),
    links: links(P.t2l)
  });
}
const out = `// Generated by build-knowledge.mjs on ${new Date().toISOString().slice(0, 10)} from assets/ask.js. Do not edit by hand.\nexport const CHUNKS = ${JSON.stringify(chunks, null, 1)};\n`;
fs.writeFileSync(path.join(here, "src", "knowledge.js"), out);
fs.writeFileSync(path.join(here, "knowledge.md"), chunks.map((c) => `## ${c.id}\n${c.text}${c.links.length ? "\nLinks: " + c.links.map((l) => `${l.t} <${l.u}>`).join("; ") : ""}`).join("\n\n") + "\n");
console.log(`Wrote ${chunks.length} chunks to src/knowledge.js and knowledge.md`);
